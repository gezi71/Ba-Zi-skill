# ─────────────────────────────────────────────────────────────
# 十二长生
# ─────────────────────────────────────────────────────────────

CHANG_SHENG_STAGES: Tuple[str, ...] = (
    "长生", "沐浴", "冠带", "临官", "帝旺", "衰", "病", "死", "墓", "绝", "胎", "养",
)

# 各天干的「长生」落在哪个地支。五阳干顺行，五阴干逆行。
# ★ 丙火与戊土同长生在寅、丁火与己土同长生在酉 —— 这是「火土同宫」的通行写法，
#   另一派认为戊土长生在寅/丙不同宫，本项目取前者。
CHANG_SHENG_START_BRANCH: Tuple[int, ...] = (
    11,  # 甲 → 亥
    6,   # 乙 → 午
    2,   # 丙 → 寅
    9,   # 丁 → 酉
    2,   # 戊 → 寅（火土同宫）
    9,   # 己 → 酉（火土同宫）
    5,   # 庚 → 巳
    0,   # 辛 → 子
    8,   # 壬 → 申
    3,   # 癸 → 卯
)


def chang_sheng_of(stem: int, branch: int) -> str:
    """某天干坐某地支，在十二长生里处于哪一 stage。"""
    start = CHANG_SHENG_START_BRANCH[stem % 10]
    forward = (stem % 2) == 0  # 阳干顺，阴干逆
    offset = (branch - start) % 12
    stage = offset if forward else (12 - offset) % 12
    return CHANG_SHENG_STAGES[stage]


# ─────────────────────────────────────────────────────────────
# 旬空（空亡）
# ─────────────────────────────────────────────────────────────

def xun_kong_of(index60: int) -> Tuple[int, int]:
    """六十甲子序号 → 旬空的两个地支 index。

    甲子旬（0-9）空戌亥，每旬往前推两位支：
        k = index // 10 → 空（10 - 2k）与（11 - 2k）
    """
    k = (index60 % 60) // 10
    start = (10 - 2 * k) % 12
    return start, (start + 1) % 12



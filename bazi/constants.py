STEMS: Tuple[str, ...] = ("甲", "乙", "丙", "丁", "戊", "己", "庚", "辛", "壬", "癸")
BRANCHES: Tuple[str, ...] = ("子", "丑", "寅", "卯", "辰", "巳", "午", "未", "申", "酉", "戌", "亥")

STEM_ELEMENTS: Tuple[str, ...] = ("木", "木", "火", "火", "土", "土", "金", "金", "水", "水")
BRANCH_ELEMENTS: Tuple[str, ...] = ("水", "土", "木", "木", "土", "火", "火", "土", "金", "金", "土", "水")

# 阴阳。注意：这是按干支序号奇偶判定的通行口径（甲丙戊庚壬为阳 / 子寅辰午申戌为阳）。
STEM_IS_YANG: Tuple[bool, ...] = tuple(i % 2 == 0 for i in range(10))
BRANCH_IS_YANG: Tuple[bool, ...] = tuple(i % 2 == 0 for i in range(12))


def stem_branch_pair(index60: int) -> Tuple[int, int]:
    """六十甲子序号 → (天干 index, 地支 index)。"""
    return index60 % 10, index60 % 12


def make_ganzhi(index60: int) -> str:
    """六十甲子序号 → 汉字，如 0 → '甲子'。"""
    s, b = stem_branch_pair(index60 % 60)
    return STEMS[s] + BRANCHES[b]


def ganzhi_index_from_pair(stem: Optional[int] = None, branch: Optional[int] = None) -> Optional[int]:
    """由天干地支反推六十甲子序号。两者都给会互相校验，组合不存在（如「甲丑」）返回 None。"""
    if stem is None and branch is None:
        return None
    if stem is not None and branch is not None:
        for i in range(60):
            if i % 10 == stem % 10 and i % 12 == branch % 12:
                return i
        return None
    raise ValueError("必须同时给天干与地支：单给一个无法确定六十甲子序号")


# ─────────────────────────────────────────────────────────────
# 五行生克
# ─────────────────────────────────────────────────────────────

ELEMENTS: Tuple[str, ...] = ("木", "火", "土", "金", "水")

# 相生：木生火 → 火生土 → 土生金 → 金生水 → 水生木
ELEMENT_SHENG: Dict[str, str] = {"木": "火", "火": "土", "土": "金", "金": "水", "水": "木"}
# 相克：木克土 → 土克水 → 水克火 → 火克金 → 金克木
ELEMENT_KE: Dict[str, str] = {"木": "土", "土": "水", "水": "火", "火": "金", "金": "木"}


def element_of_stem(stem: int) -> str:
    return STEM_ELEMENTS[stem % 10]


def element_of_branch(branch: int) -> str:
    return BRANCH_ELEMENTS[branch % 12]



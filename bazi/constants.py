"""
八字排盘用到的全部常量与规则表。

本文件的组织原则：**凡是「口诀」，都必须写成数据，而不是写成 if/else 分支。**

理由有两个：
  1. 口诀是可以被核对的 —— 一张表摆在这儿，任何人拿《渊海子平》对照一眼就能查出写漏的；
     写成分支逻辑之后，错误会藏在控制流里，几年都没人发现。
  2. 各家流派对同一口诀常有分歧（比如神煞的起法、晚子时的归属）。
     写成分散的 if 就没法「换一套表」，写成数据就可以让调用方选择流派。

索引约定（全仓统一，务必牢记）：
    天干 index 0-9  : 甲乙丙丁戊己庚辛壬癸
    地支 index 0-11 : 子丑寅卯辰巳午未申酉戌亥
    干支组合 index 0-59 = 甲子起算的第 n 位（甲子=0，乙丑=1，…，癸亥=59）
"""


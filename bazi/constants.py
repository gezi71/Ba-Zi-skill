    assert len(NAYIN) == 30, f"纳音表应有 30 组，实为 {len(NAYIN)}"
    assert len(NAYIN_ELEMENTS) == 30, f"纳音五行表应有 30 项，实为 {len(NAYIN_ELEMENTS)}"
    assert len(STEMS) == 10 and len(BRANCHES) == 12
    assert len(CHANG_SHENG_START_BRANCH) == 10
    assert len(HIDDEN_STEMS) == 12
    # 六十甲子每个 index 都必须能取到纳音，且 names/元素 一一对应
    for i in range(60):
        assert 0 <= i // 2 < len(NAYIN)
        assert len(NAYIN[i // 2]) == 3



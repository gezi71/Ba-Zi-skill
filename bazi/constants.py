# ─────────────────────────────────────────────────────────────

SHI_SHEN_NAMES: Tuple[str, ...] = (
    "比肩", "劫财", "食神", "伤官", "偏财", "正财", "七杀", "正官", "偏印", "正印",
)


def shi_shen_of(day_stem: int, other_stem: int) -> str:
    """日主看另一天干所得的十神。

    判定次序必须严格是「先看生克关系，再看阴阳同异」：
      同我者：比肩（同性）/ 劫财（异性）
      我生者：食神（同性）/ 伤官（异性）
      我克者：偏财（同性）/ 正财（异性）
      克我者：七杀（同性）/ 正官（异性）
      生我者：偏印（同性）/ 正印（异性）

    ★ 正偏的判定是「同异性」而非「阴阳强弱」：
      例如日主甲（阳木）见乙（阴木）→ 同为木但阴阳不同 → 劫财（不是比肩）。
    """
    mine = element_of_stem(day_stem)
    theirs = element_of_stem(other_stem)
    same_polarity = (day_stem % 2) == (other_stem % 2)
    yang = 0 if same_polarity else 1  # 0=同性→偏神之一支, 1=异性→正神之一支

    if theirs == mine:
        return "比肩" if same_polarity else "劫财"
    if ELEMENT_SHENG[mine] == theirs:          # 我生
        return "食神" if same_polarity else "伤官"
    if ELEMENT_KE[mine] == theirs:             # 我克
        return "偏财" if same_polarity else "正财"
    if ELEMENT_KE[theirs] == mine:             # 克我
        return "七杀" if same_polarity else "正官"
    return "偏印" if same_polarity else "正印"  # 生我


def shi_shen_of_element(day_stem: int, other_element: str, other_is_yang: bool) -> str:
    """把地支藏干当成「虚拟天干」求十神 —— 手里只有五行与阴阳时用这个。

    地支藏干本来就是天干，直接用 `shi_shen_of(day_stem, hidden_stem)` 即可；
    但在做一些统计（比如统计日主有没有根）时，手边只有元素信息，这里提供同一个判定口径。
    """
    mine = element_of_stem(day_stem)
    same_polarity = (day_stem % 2) == (0 if other_is_yang else 1)
    target = other_element
    if target == mine:
        return "比肩" if same_polarity else "劫财"
    if ELEMENT_SHENG[mine] == target:
        return "食神" if same_polarity else "伤官"
    if ELEMENT_KE[mine] == target:
        return "偏财" if same_polarity else "正财"
    if ELEMENT_KE[target] == mine:
        return "七杀" if same_polarity else "正官"
    return "偏印" if same_polarity else "正印"



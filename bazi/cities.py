# 同名防御：`name -> [(qualified, lon), ...]` 全量索引，便于提示歧义
def build_flat_index() -> Dict[str, List[Tuple[QualifiedName, float]]]:
    """返回 名字 -> [(限定名, 经度)]，同名条目会积累到同一 key。"""
    index: Dict[str, List[Tuple[QualifiedName, float]]] = {}

    def push(key: str, qualified: str, lon: float) -> None:
        index.setdefault(key, []).append((qualified, lon))

    for province, cities in PROVINCES.items():
        for name, lon in cities:
            push(name, f"{province}/{name}", lon)
            # 去掉省名后缀再索引一次，让「广东」也能命中
            short = province
            for suffix in ("特别行政区", "维吾尔自治区", "壮族自治区", "回族自治区", "自治区", "省", "市"):
                if short.endswith(suffix) and len(short) > len(suffix):
                    short = short[: -len(suffix)]
                    break
            push(f"{short}/{name}", f"{province}/{name}", lon)
    for name, lon in OVERSEAS_CITIES:
        push(name, f"海外/{name}", lon)
    return index

CITY_INDEX = build_flat_index()

def lookup_city(name: str) -> List[Tuple[QualifiedName, float]]:
    """按名字查经度，返回**全部**命中项（含同名歧义），由调用方决定如何消歧。

    支持的写法，从最宽到最严：
      · 城市名        -> 广州 / 朝阳
      · 简写省/城市    -> 广东/广州 / 新疆/喀什
      · 全限定名      -> 广东省/广州 / 新疆维吾尔自治区/喀什

    同名歧义是真实存在的：全国有多个「西安」「城关」「新区」，
    经度差最多能到 10° 以上（≈ 40 分钟真太阳时），足以换时辰。
    这里宁可返回多条让用户选，也不猜 —— 猜错了时柱就整个错了。
    """
    key = name.strip()
    if not key:
        return []

    hits = list(CITY_INDEX.get(key, []))
    if hits:
        return hits

    # 输入可能带行政区划后缀（「朝阳区」「/home/user」之类），逐级剥尾巴再试。
    # 例：北京市朝阳区 -> 北京市朝阳 -> 北京朝阳? 都不在表里时，最后退化按城市后缀匹配。
    for suffix in ("特别行政区", "维吾尔自治区", "壮族自治区", "回族自治区",
                   "自治区", "地区", "盟", "自治州", "市", "省", "县", "区", "旗", "镇"):
        if key.endswith(suffix) and len(key) > len(suffix):
            stripped = key[: -len(suffix)]
            hits = list(CITY_INDEX.get(stripped, []))
            if hits:
                return hits

    # 最后兜底：表里城市名是输入的前缀（「朝阳」匹配「朝阳区」→ 反向，用 startswith）
    return [(q, lon) for k, v in CITY_INDEX.items() if "/" not in k
            and k.startswith(key) for q, lon in v]


def all_city_names() -> List[str]:
    """全部可输入的城市名（用于 CLI 的错误提示）。"""
    return sorted({k for k in CITY_INDEX if "/" not in k})

